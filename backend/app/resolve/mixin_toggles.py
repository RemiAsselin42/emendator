"""Generate mod-own mixin-toggle overrides — the fix ladder's lowest-risk rung.

When a mod ships its own per-mixin kill switch (CaffeineMC-style properties,
Debugify's json — detected into :class:`MixinToggleSystem` by the analyzer),
disabling exactly the conflicting mixin through *that* mechanism is the
officially tolerated path: no jar edits, survives updates, reversible by
deleting the generated file.

Pure functions (system + mixin classes -> file artifact), like
:mod:`app.resolve.generate`. Caveats the caller must surface:

- CaffeineMC keys are per *package*: the smallest togglable unit may cover a
  few sibling mixins, and a mod's own overrides can outrank the user file.
- Writing the file replaces prior user toggles at that path — apply-time
  merging is the pipeline's job (Phase 2.5), not this generator's.
"""

import json

from app.analyzer.detectors import MixinToggleSystem
from app.models import GeneratedFile

_HEADER = (
    "# Generated by Emendator — disables only the conflicting mixins.\n"
    "# Delete this file (or flip values back to true) to undo.\n"
)


def generate_mixin_toggles(
    system: MixinToggleSystem, mixin_classes: set[str]
) -> GeneratedFile | None:
    """The override file disabling ``mixin_classes`` through the mod's own system.

    Returns None when none of the classes is togglable (no key coverage) —
    callers then fall to the next ladder rung (filter config / rollback /
    disable).
    """
    keys = sorted({system.keys[cls] for cls in mixin_classes if cls in system.keys})
    if not keys:
        return None
    if system.kind == "debugify":
        content = json.dumps({key: False for key in keys}, indent=2) + "\n"
    else:
        content = _HEADER + "".join(f"{key}=false\n" for key in keys)
    return GeneratedFile(path=system.file, content=content)


def togglable_classes(system: MixinToggleSystem | None, mixin_classes: set[str]) -> set[str]:
    """Which of ``mixin_classes`` this system can actually switch off."""
    if system is None:
        return set()
    return {cls for cls in mixin_classes if cls in system.keys}
